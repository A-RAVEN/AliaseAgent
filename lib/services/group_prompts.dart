// 群聊的两段提示词纪律（change `agent-group-chat` 任务 4.6 / design D6）。
//
// 写成**代码常量**的理由：文档守卫与单测能断言"提示词里真的写了这几句"，否则
// 「纪律只写在 spec 里」无法验证。
//
// 两段纪律严格分工：
//   - 成员角色说明：给**公开回复**用（它会被其他成员读到）⇒ 含"自包含 + 文件指针"。
//   - 摘要纪律：摘要私有、跨成员不读 ⇒ **只**要求保留归属，不能带自包含要求。

/// 附加在成员系统提示词之后的组角色说明（五件事齐备）。
///
/// 1. 他人以「Y 说：」出现在 user 轮；
/// 2. 自己的历史以 assistant 轮呈现；
/// 3. 他人的工具过程不可见；
/// 4. **公开回复**必须自包含（结论 + 文件指针）；
/// 5. 共享工作区是成员间真正的协调通道。
///
/// 第 4 条的"先例原文"来自 `kSubagentRolePrompt`：「结束时只输出一段自包含的最终结论
/// （必要的背景、」+「结论与文件路径都写清楚）」—— 这里把它从"子 Agent 的最终结论"
/// 泛化到"成员的每一次公开回复"。
const String kGroupMemberRolePrompt = '你是一个群聊组的成员，和用户以及其它成员共享同一段对话。'
    '几点说明：'
    '(1) 其他成员的公开回复会以 user 轮出现，正文以「某某 说：」开头——那是别人说的话，不是你自己的话；'
    '(2) 你自己此前的回复以 assistant 轮出现，是你的第一人称历史；'
    '(3) 你看不到其他成员的思考与工具过程，他们同样看不到你的；'
    '(4) 你的每一次公开回复都必须自包含：写清结论（必要的背景、结论与文件路径都写清楚），'
    '因为其他成员只能读到你的公开回复、读不到你的工具过程；'
    '(5) 共享工作区是成员之间真正的协调通道：要在文件里落下可被他人读到的证据与路径。';

/// 摘要请求追加的**归属**纪律（只有归属，不含"自包含 + 文件指针"）。
///
/// 摘要以成员自己的视角写，但被折叠文本里他人的话必须保持「Y 说」，不得改写成
/// 第一人称 —— 否则 B 的摘要会把 A 的发言记成自己的。
const String kGroupSummaryPromptSuffix = '这次摘要来自一个群聊组的成员视角：'
    '被折叠的文本里以「某某 说：」开头的内容是**其他成员**的发言，'
    '摘要时必须原样保留「某某 说：」这种归属，不得把它们改写成第一人称。';

/// **开启态自愿反应轮**追加的纪律（change `group-reactive-mode` R.9 / design D6）。
///
/// 采用「**默认沉默**」框架：沉默是常态、发言是例外。用户实测旧版「没有贡献就
/// 输出 [PASS]」不生效（模型永远接话），R.9/R.10 改成结构化终态工具 + 强烈授权沉默。
/// 七件事缺一不可：
///   ① 默认沉默：大多数轮 `pass: true`；`pass=true` 不是失败，是群聊礼仪；
///   ② 只有**非说不可、别人没说过的实质新信息**才 `pass: false`；
///   ③ 3–4 个该 `pass=true` 的 few-shot 情形（别人已说过 / 纯表态 / 已收尾 / 与角色无关）；
///   ④ 相关性门槛（只反应真正新且与你相关的信息）；
///   ⑤ 必须调用 `group_react` 恰好一次，`message` 是唯一公开内容；
///   ⑥ 正文不写「我 PASS / 我不发言」这类元话术；
///   ⑦ 发言要自包含（结论 + 文件指针），有依据的同意 / 反对 / 补充 / 提问才算贡献。
///
/// 写成代码常量而不是只写进 spec：单测与文档守卫能逐字断言「提示词里真的写了这几句」。
const String kGroupReactionPrompt = '这一轮你是在**自发反应**：对组里刚刚出现的公开消息做判断，决定要不要接话。'
    '**默认沉默**：沉默是常态、发言是例外。大多数轮你都应当返回 '
    'group_react {pass: true, message: ""}。只有当你有一条**非说不可、别人没说过的实质新信息**时，'
    '才返回 group_react {pass: false, message: "..."}。'
    'pass=true 不是失败，是群聊礼仪——没有新贡献就不该占公开时间线。'
    '以下情形都应当返回 pass=true：'
    '(1) 别人已经表达过类似观点（哪怕你想换个说法）；'
    '(2) 你只是纯表态、没有新依据（例如只说"同意"或"说得好"）；'
    '(3) 对话已经充分收尾，没有需要补充的结论或风险；'
    '(4) 与你的角色/职责无关。'
    '相关性门槛：只反应真正新的、与你相关的信息；其余一律 pass=true。'
    '结构化纪律：本轮必须调用 group_react 恰好一次；message 是唯一会公开的内容'
    '（pass=true 时被忽略）。不要在正文里写「我 PASS」「我不发言」之类元话术——'
    '正文不会进入公开时间线，写了也没用；没有调用 group_react 会被判为失败。'
    '决定发言（pass=false）时，message 要自包含：结论、必要的背景与文件指针都写清楚；'
    '有依据的同意、有依据的反对、有信息量的补充、真正需要澄清的提问才算贡献；'
    '别人已经说过的内容不复述。';

/// **强制轮**追加的纪律（开启态 speaker 强制轮 + 两态下 `@mention` 强制轮）。
///
/// 与 [kGroupReactionPrompt] 严格分工：这一段**不含** `pass=true` 的沉默授权
/// （不出现「没有话说就 pass=true」这类许可），否则「必须回应」与「可以沉默」会
/// 互相抵消（design D6）。它要求用 `group_react {pass: false, message}` 交付回应；
/// 结构化检测（`pass=true` / 空 `message` 记 forced_pass / forced_empty）是防御措施，
/// 不是给模型的许可。**R.9 不修改它的必应口径。**
const String kGroupMustRespondPrompt = '这一轮**用户点名了你**：必须给出一个实质回应，'
    '不允许用沉默或只说"收到"敷衍过去。'
    '按你这一轮真正看到的内容给出有价值的判断或具体动作；不要回避，也不要重复别人已经说过的内容。'
    '保持自包含：结论、必要的背景与文件指针都写清楚。'
    '结束本轮时调用 group_react 恰好一次：pass 必须为 false，message 写你的实质回应'
    '（它是唯一会公开的内容）；不要用正文代替 message，'
    '也不要在正文里写「我不发言」之类元话术。';
